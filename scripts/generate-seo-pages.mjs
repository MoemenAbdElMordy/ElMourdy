function replaceMeta(html, selector, value) {
  const escapedSelector = selector.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  return html.replace(
    new RegExp(`(<meta[^>]+${escapedSelector}[^>]+content=")[^"]*(")`, "i"),
    `$1${value}$2`,
  );
}

